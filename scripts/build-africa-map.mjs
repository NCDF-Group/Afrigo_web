// Generates src/components/site/africaMapData.ts from Natural Earth 1:110m data (world-atlas, public domain).
// Run: node scripts/build-africa-map.mjs — output is static SVG paths, so the site ships no map libraries.
import { readFileSync, writeFileSync } from 'fs'
import { feature } from 'topojson-client'
import { geoMercator, geoPath, geoCentroid } from 'd3-geo'

const WIDTH = 800
const HEIGHT = 860

// ISO 3166-1 numeric → display name for the 55 African Union members (plus Western Sahara territory).
const COUNTRIES = {
  '012': 'Algeria', '024': 'Angola', '204': 'Benin', '072': 'Botswana', '854': 'Burkina Faso', '108': 'Burundi',
  '132': 'Cabo Verde', '120': 'Cameroon', '140': 'Central African Republic', '148': 'Chad', '174': 'Comoros',
  '178': 'Republic of the Congo', '180': 'DR Congo', '384': "Côte d'Ivoire", '262': 'Djibouti', '818': 'Egypt',
  '226': 'Equatorial Guinea', '232': 'Eritrea', '748': 'Eswatini', '231': 'Ethiopia', '266': 'Gabon', '270': 'The Gambia',
  '288': 'Ghana', '324': 'Guinea', '624': 'Guinea-Bissau', '404': 'Kenya', '426': 'Lesotho', '430': 'Liberia',
  '434': 'Libya', '450': 'Madagascar', '454': 'Malawi', '466': 'Mali', '478': 'Mauritania', '480': 'Mauritius',
  '504': 'Morocco', '508': 'Mozambique', '516': 'Namibia', '562': 'Niger', '566': 'Nigeria', '646': 'Rwanda',
  '678': 'São Tomé and Príncipe', '686': 'Senegal', '690': 'Seychelles', '694': 'Sierra Leone', '706': 'Somalia',
  '710': 'South Africa', '728': 'South Sudan', '729': 'Sudan', '834': 'Tanzania', '768': 'Togo', '788': 'Tunisia',
  '800': 'Uganda', '894': 'Zambia', '716': 'Zimbabwe', '732': 'Western Sahara'
}

// Island states too small for 1:110m — drawn as dots at these [lon, lat] positions.
const ISLANDS = { '132': [-23.6, 15.1], '174': [43.9, -11.9], '480': [57.55, -20.25], '678': [6.6, 0.25], '690': [55.45, -4.65] }

// Trade hubs used for route lines, [lon, lat].
const HUBS = {
  dakar: ['Dakar', -17.47, 14.72], banjul: ['Banjul', -16.58, 13.45], bissau: ['Bissau', -15.6, 11.86], conakry: ['Conakry', -13.58, 9.64],
  freetown: ['Freetown', -13.23, 8.48], monrovia: ['Monrovia', -10.8, 6.3], abidjan: ['Abidjan', -4.01, 5.36], accra: ['Accra', -0.19, 5.6],
  lome: ['Lomé', 1.22, 6.13], cotonou: ['Cotonou', 2.43, 6.37], lagos: ['Lagos', 3.38, 6.52], kano: ['Kano', 8.52, 12.0],
  casablanca: ['Casablanca', -7.59, 33.57], cairo: ['Cairo', 31.24, 30.04], addis: ['Addis Ababa', 38.74, 9.03], nairobi: ['Nairobi', 36.82, -1.29],
  kinshasa: ['Kinshasa', 15.31, -4.32], johannesburg: ['Johannesburg', 28.05, -26.2], douala: ['Douala', 9.7, 4.05]
}

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)))
const all = feature(topo, topo.objects.countries).features
// Natural Earth splits Somaliland from Somalia; draw it as part of Somalia.
const africa = all
  .map(f => (!f.id && f.properties.name === 'Somaliland' ? { ...f, id: '706' } : f))
  .filter(f => f.id && COUNTRIES[f.id])

// Fit mainland shapes and the island dots so every member state is on the canvas.
const islandPoints = { type: 'Feature', geometry: { type: 'MultiPoint', coordinates: Object.values(ISLANDS) } }
const projection = geoMercator().fitExtent([[16, 16], [WIDTH - 16, HEIGHT - 16]], { type: 'FeatureCollection', features: [...africa, islandPoints] })
const path = geoPath(projection)
const round = d => d.replace(/-?\d+\.\d+/g, n => (+n).toFixed(1))
const point = ([lon, lat]) => projection([lon, lat]).map(v => +v.toFixed(1))

const shapes = {}
for (const f of africa) shapes[f.id] = (shapes[f.id] || '') + round(path(f))

const countries = Object.entries(COUNTRIES)
  .map(([id, name]) => {
    const island = ISLANDS[id]
    const shape = africa.find(f => f.id === id)
    if (!shape && !island) return null
    const [x, y] = island ? point(island) : point(geoCentroid(shape))
    return { id, name, d: shapes[id] || null, x, y }
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name))

const hubs = Object.fromEntries(Object.entries(HUBS).map(([key, [name, lon, lat]]) => [key, { name, ...Object.fromEntries(['x', 'y'].map((k, i) => [k, point([lon, lat])[i]])) }]))

const output = `// Generated by scripts/build-africa-map.mjs from Natural Earth 1:110m (public domain). Do not edit by hand.
export type MapCountry = { id: string; name: string; d: string | null; x: number; y: number }
export type MapHub = { name: string; x: number; y: number }

export const MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'

export const MAP_COUNTRIES: MapCountry[] = ${JSON.stringify(countries)}

export const MAP_HUBS = ${JSON.stringify(hubs)} as const satisfies Record<string, MapHub>
`
writeFileSync(new URL('../src/components/site/africaMapData.ts', import.meta.url), output)
console.log(`Wrote ${countries.length} countries (${countries.filter(c => !c.d).length} as dots), ${Object.keys(hubs).length} hubs, ${(output.length / 1024).toFixed(1)} KB`)
